#pragma once
#include "../../src/game/original_racer_material50km.h"
#include <cstddef>
#include <cstdint>
#include <vector>

namespace ra_static_lighting50LA {
class Binding;
// Explicit native policy, not a claim that a static model constructor or its
// flags1F4/ambient/alpha override setters have executed.
enum class StaticDiffusePolicy : std::uint8_t { selectedMatrixWithoutModelOverrides };
enum class StaticDiffuseStatus : std::uint8_t {
    complete,stale,source,material,fillUnsupported,normal,arithmetic,allocation
};
struct StaticDiffuseDiagnostic {
    StaticDiffuseStatus status=StaticDiffuseStatus::complete;
    std::size_t surface=0,vertex=0;
};
// Metadata is copied out, never a draw permission or a borrowed vector view.
struct StaticDiffuseSurface {
    StaticDiffusePolicy policy=StaticDiffusePolicy::selectedMatrixWithoutModelOverrides;
    std::size_t surface=0,placement=0,worldInstance=0,raster=0;
    std::int32_t materialRow=-1;
    std::int16_t programToken=-1;
    std::uint32_t vertexStart=0,vertexCount=0,indexStart=0,indexCount=0;
    std::uint64_t cameraGeneration=0,cameraPublication=0,cameraFrame=0;
};
// Separate generated bytes, never written into the source/prelit vertex bank.
// Only the actual Binding may construct, publish or read this owner. It remains
// inside that nonmovable Binding and dies before its world/light/camera pins.
class StaticDiffuseStream final {
    friend class Binding;
    struct Surface {
        StaticDiffuseSurface identity;
        std::vector<rr::game::original_racer_lighting50KM::DiffuseVertexRgba> vertices;
    };
    std::vector<Surface> surfaces_;
    // Immutable row-shape summary only; live raster admission is never cached.
    bool allRastersEqual_=true;
    StaticDiffuseStream()=default;
public:
    ~StaticDiffuseStream()=default;
    StaticDiffuseStream(const StaticDiffuseStream&)=delete;
    StaticDiffuseStream& operator=(const StaticDiffuseStream&)=delete;
};
}
