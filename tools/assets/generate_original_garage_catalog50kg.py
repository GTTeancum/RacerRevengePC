"""Reproduce authenticated Garage member metadata, never extract original assets.

The only optional output is a C++ catalog of names, bounded extents and hashes.
Archive entry names never determine an output path. Existing archive IDs and
members are untouched. A successful check proves cold identity, not UI readiness.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/gameplay"))
from recover48b import unpack_resource

ARCHIVES = (
    ("UI/UIGARAGE/UIGARAGE.RES", 1926215,
     "fdc7af917de37df46c3801323092e7abde1a2056df242825faf3e4b45fef57da", 170, 6168576),
    ("UI/UIGARAGE/19E.RES", 116288,
     "72d443450ac68811cbd75491357d730ed9715478864957abd77a8bac56d760c6", 4, 270336),
)
DESTINATION = ROOT / "src/assets/original_ui_garage_member_catalog50kg.inc"


def catalog(disc):
    lines = ["// NEW reconstruction: authenticated disc metadata, not original asset data.",
             "// Generated by tools/assets/generate_original_garage_catalog50kg.py.",
             "// Append in original archive/member order; do not sort or deduplicate."]
    for name, size, digest, count, extent in ARCHIVES:
        path = disc / name
        if path.stat().st_size != size:
            raise ValueError(f"{name}: archive byte size mismatch")
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"{name}: archive identity mismatch")
        entries, _, decoded = unpack_resource(data)
        if len(entries) != count or len(decoded) != extent:
            raise ValueError(f"{name}: member count/decoded extent mismatch")
        lines.append(f"// {name}: {count} members; SHA-256 {digest}")
        for entry in entries:
            offset, length = entry["logical_offset"], entry["bytes"]
            if offset > extent or length > extent - offset:
                raise ValueError(f"{name}: member extent mismatch")
            sha = hashlib.sha256(decoded[offset:offset + length]).hexdigest()
            lines.append("    {%s, %du, %du, \"%s\"}," %
                         (json.dumps(entry["name"]), offset, length, sha))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc_root", type=Path)
    parser.add_argument("--write", action="store_true", help="write the fixed metadata-only catalog path")
    args = parser.parse_args()
    output = catalog(args.disc_root)
    if args.write:
        DESTINATION.write_text(output, encoding="ascii")
    elif DESTINATION.read_text(encoding="ascii") != output:
        raise ValueError("Generated Garage catalog differs from authenticated metadata")
    print("Garage cold catalog verified: 2 archives, 174 original-order members; no original asset output")


if __name__ == "__main__":
    main()
