ELF_SHA = 'c1f1b63eb422b624189e68eb0140b318455e341d73182703017298fea6ce6c30'
RAM_SHA = '38682d69c2e2cc08ad1a52367a5198f88ec8624d232c2195fb267050928d3e48'
