"""Bounded offline recovery of the original rigid body integration core.

Does not execute the game or alter original inputs. Regenerates test-only words
and evidence exclusively beneath the current 48C-owned paths.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import struct

ELF_SHA = 'c1f1b63eb422b624189e68eb0140b318455e341d73182703017298fea6ce6c30'
RAM_SHA = '38682d69c2e2cc08ad1a52367a5198f88ec8624d232c2195fb267050928d3e48'
RAM_PATH = 'work/native-run47w-1-1-1-1-1-0-1-1-1-1-20260930-181624-483/ee.bin'
BLOCKS = [('body', 0x167cd4, 0x1680f4), ('integrator', 0x14ee40, 0x14eeb8),
          ('quaternion_derivative', 0x14f7b0, 0x14f870), ('quaternion_normalize', 0x14f410, 0x14f4f0)]
SOURCES = ['FUN_00167c40_0x167c40.cpp', 'entry_0014ee40_0x14ee40.cpp',
           'entry_0014ee6c_0x14ee6c.cpp', 'entry_0014eeb0_0x14eeb0.cpp',
           'FUN_0014f7b0_0x14f7b0.cpp', 'FUN_0014f410_0x14f410.cpp',
           'FUN_00219810_0x219810.cpp', 'FUN_001a0570_0x1a0570.cpp',
           'FUN_00127bb0_0x127bb0.cpp', 'FUN_001a1a20_0x1a1a20.cpp',
           'FUN_00217de0_0x217de0.cpp', 'entry_001a8060_0x1a8060.cpp',
           'FUN_002827d0_0x2827d0.cpp', 'FUN_00143600_0x143600.cpp',
           'FUN_00143700_0x143700.cpp']

def sha(b): return hashlib.sha256(b).hexdigest()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    root = ap.parse_args().root.resolve()
    elf_path = root / 'work/native/project/disc/SLUS_202.68'
    elf, ram = elf_path.read_bytes(), (root / RAM_PATH).read_bytes()
    assert sha(elf) == ELF_SHA and sha(ram) == RAM_SHA, 'input hash changed'
    def elf_bytes(va, size):
        offset = va - 0x100000 + 0x80
        assert 0 <= offset <= len(elf)-size
        return elf[offset:offset+size]
    def u32(a): return struct.unpack_from('<I', ram, a)[0]
    def floats(a, n): return list(struct.unpack_from('<'+'f'*n, ram, a))
    out = root / 'evidence/gameplay48C'
    out.mkdir(parents=True, exist_ok=True)
    header = ['// Generated by recover48c.py. TEST ONLY; exact original ELF words.',
              '#pragma once', '#include <cstdint>']
    manifest = {'elf': {'path': str(elf_path.relative_to(root)), 'sha256': ELF_SHA},
                'ram': {'path': RAM_PATH, 'sha256': RAM_SHA}, 'blocks': [], 'source_files': []}
    for name, start, end in BLOCKS:
        raw = elf_bytes(start, end-start)
        words = struct.unpack('<'+'I'*(len(raw)//4), raw)
        header += [f'inline constexpr std::uint32_t rr_{name}_48c_start = 0x{start:x}u;',
                   f'inline constexpr std::uint32_t rr_{name}_48c[] = {{']
        for i in range(0, len(words), 8):
            header += ['    ' + ', '.join(f'0x{x:08x}u' for x in words[i:i+8]) + ',']
        header += ['};']
        (out / f'{name}.bin').write_bytes(raw)
        manifest['blocks'].append({'name': name, 'start': hex(start), 'end_exclusive': hex(end),
                                   'file_offset': hex(start-0x100000+0x80), 'sha256': sha(raw)})
    # Compare every available disassembly annotation to the immutable ELF.
    for filename in SOURCES:
        p = root / 'work/native/project/generated' / filename
        selected, seen = [], set()
        for line_no, line in enumerate(p.read_text().splitlines(), 1):
            m = re.match(r'\s*// (0x[0-9a-f]+): (0x[0-9a-f]+)\s+(.*)', line)
            if not m: continue
            pc, word = int(m[1], 16), int(m[2], 16)
            assert struct.unpack('<I', elf_bytes(pc, 4))[0] == word, (filename, line_no)
            if pc not in seen:
                selected.append(f'{line_no}: {line.strip()}')
                seen.add(pc)
        (out / (filename+'.instructions.txt')).write_text('\n'.join(selected)+'\n')
        manifest['source_files'].append({'path': str(p.relative_to(root)), 'sha256': sha(p.read_bytes()),
                                        'verified_unique_words': len(seen)})
    player, body = 0xc5b0b0, 0xd110a0
    assert u32(player+0x340) == body and u32(body+8) == 0x3ce000
    assert u32(0x3ce000+0x3c) == 0x167c40 and u32(body+0x290) == 0x14ee40
    raw = ram[body:body+0x320]
    (out/'stopped_player_body.bin').write_bytes(raw)
    words = struct.unpack('<'+'I'*(len(raw)//4), raw)
    header += ['inline constexpr std::uint32_t rr_stopped_body_48c[] = {']
    for i in range(0, len(words), 8):
        header += ['    ' + ', '.join(f'0x{x:08x}u' for x in words[i:i+8])+',']
    header += ['};']
    constants = {'zero_quaternion': {'va': '0x382b60', 'elf': list(struct.unpack('<4I', elf_bytes(0x382b60,16))),
                                    'ram': [u32(0x382b60+i*4) for i in range(4)]},
                 'zero_vector': {'va': '0x433b80', 'ram': [u32(0x433b80+i*4) for i in range(4)]}}
    assert constants['zero_quaternion']['elf'] == constants['zero_quaternion']['ram'] == [0]*4
    assert constants['zero_vector']['ram'] == [0,0,0,0x3f800000]
    fields = {'mass':0x26c, 'inverse_mass':0x270, 'linear_acceleration_limit_squared':0x274,
              'angular_acceleration_limit_squared':0x278, 'linear_velocity_limit_squared':0x27c,
              'angular_velocity_limit_squared':0x280}
    vectors = {'position':(0x60,3), 'velocity':(0x70,3), 'angular_velocity':(0xb0,3),
               'linear_acceleration':(0xc0,3), 'angular_acceleration':(0xd0,3),
               'force':(0x180,3), 'torque':(0x190,3), 'orientation':(0x1f0,4),
               'previous_position_derivative':(0x2c4,3), 'previous_linear_acceleration':(0x2dc,3),
               'previous_orientation_derivative':(0x2f8,4), 'previous_angular_acceleration':(0x314,3)}
    snapshot = {'status':'stopped end-of-run snapshot, NOT a tick entry/exit pair',
                'player':hex(player),'body':hex(body),'integrator':'0x14ee40','constants':constants,
                'fields':{k:{'offset':hex(o),'value':floats(body+o,1)[0],'bits':hex(u32(body+o))} for k,o in fields.items()},
                'vectors':{k:{'offset':hex(o),'values':floats(body+o,n),'bits':[hex(u32(body+o+i*4)) for i in range(n)]} for k,(o,n) in vectors.items()},
                'components':[]}
    for off in [0x340,0x344,0x34c,0x350,0x354,0x358,0x35c,0x36c]:
        ptr = u32(player+off); vt=u32(ptr+8)
        assert ram[vt:vt+0x60] == elf_bytes(vt,0x60), 'component vtable mismatch'
        ti=u32(vt); name=u32(ti)
        assert struct.unpack('<I',elf_bytes(ti,4))[0] == name
        class_name=elf_bytes(name,128).split(b'\0')[0].decode('ascii')
        snapshot['components'].append({'offset':hex(off),'object':hex(ptr),'vtable':hex(vt),
                                       'class_name':class_name,
                                       'update_slot_3c':hex(u32(vt+0x3c)), 'slot_78':hex(u32(vt+0x78))})
    snapshot['inertia_columns']=[floats(body+0x140+i*16,3) for i in range(3)]
    snapshot['body_entry_dependencies']={'enabled_field_204':u32(body+0x204),
                                          'associated_scene_object_288':hex(u32(body+0x288)),
                                          'translation_enabled':[u32(body+0x2a0+i*4) for i in range(3)],
                                          'rotation_enabled':[u32(body+0x2ac+i*4) for i in range(3)]}
    input_device=u32(player+0xff0); settings=u32(u32(0x382b80)+0x2dc)
    controller=u32(player+0xffc)
    snapshot['input']={'device':hex(input_device),'controller_index':controller,
        'button_dispatch':hex(u32(u32(input_device+0x18)+0x10)),
        'axes':[{'player_offset':hex(o),'object':hex(u32(player+o)),
                 'source_id':u32(u32(player+o)+8), 'value':floats(u32(player+o)+0x24,1)[0]}
                for o in [0xfe0,0xfe4,0xfe8,0xfec]],
        'settings_pointer':hex(settings),
        'button_bindings':{'B7C':{'settings_offset':'0x694+40*controller','source_id':u32(settings+0x694+40*controller)},
                           'B80':{'settings_offset':'0x690+40*controller','source_id':u32(settings+0x690+40*controller)}},
        'note':'Source IDs and output fields are proven; physical pad/button names and all action meanings remain unclosed.'}
    (out/'snapshot-identification.json').write_text(json.dumps(snapshot,indent=2)+'\n')
    header_path=root/'tools/gameplay/physics_words48c.h'
    header_path.write_text('\n'.join(header)+'\n')
    manifest['fixture_header']={'path':str(header_path.relative_to(root)), 'sha256':sha(header_path.read_bytes())}
    manifest['snapshot_body_sha256']=sha(raw)
    manifest['scheduler_pointer_search']={
        'target':'0x1a7b40', 'segment_file_offset':'0x80', 'segment_virtual_address':'0x100000',
        'segment_bytes':2972160,
        'direct_jal_sites':[hex(off-0x80+0x100000) for off in range(0x80,0x80+2972160,4)
                            if struct.unpack_from('<I',elf,off)[0]==(0x0c000000|(0x1a7b40>>2))],
        'aligned_pointer_sites':[hex(off-0x80+0x100000) for off in range(0x80,0x80+2972160,4)
                                  if struct.unpack_from('<I',elf,off)[0]==0x1a7b40]}
    reference=root/'work/native/sources/src/PS2Recomp/ps2xRuntime/include/ee_sqrt14.h'
    manifest['sqrt_reference']={'path':str(reference.relative_to(root)), 'sha256':sha(reference.read_bytes())}
    (out/'recovery-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'blocks':len(BLOCKS),'source_files_verified':len(SOURCES),
                      'body_fixture_sha256':sha(raw),'fixture_header_sha256':sha(header_path.read_bytes())}))

if __name__ == '__main__': main()
